#!/usr/bin/env python3
"""Build the one settings file Vorssaint reads, and restart it to apply.

Vorssaint (3.4.4+) reads ~/.config/vorssaint/settings.plist at every launch and
overlays the keys it lists. It reads only that one file, so this merges the
repo's dotfiles/config/vorssaint/settings.plist with the untracked
~/.config/vorssaint/settings.private.plist (private keys win) and writes the
result there.

Used two ways:
  - by setup's keybinds module (merge only; setup handles the restart itself);
  - standalone by the com.devenv.vorssaint-settings LaunchAgent, which runs it
    whenever either source file changes: it rewrites the file and, if the result
    changed and Vorssaint is running, restarts Vorssaint so it takes effect.

Stdlib only, so the LaunchAgent can run it with /usr/bin/python3 outside the
devenv package.
"""

from __future__ import annotations

import plistlib
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path
from xml.parsers.expat import ExpatError

REPO_DIR = Path(__file__).resolve().parents[1]
SHARED_REL = Path("dotfiles/config/vorssaint/settings.plist")  # under the repo
SHARED = REPO_DIR / SHARED_REL
CONFIG_DIR = Path.home() / ".config/vorssaint"
TARGET = CONFIG_DIR / "settings.plist"
PRIVATE = CONFIG_DIR / "settings.private.plist"
GENERATED_MARKER = "GENERATED by devenv-macos"

PRIVATE_TEMPLATE = """\
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!--
  ~/.config/vorssaint/settings.private.plist: machine-specific Vorssaint
  settings, NOT tracked in devenv-macos.

  Merged on top of the repo's dotfiles/config/vorssaint/settings.plist (keys
  here win) into ~/.config/vorssaint/settings.plist, which Vorssaint reads at
  launch. Add keys inside the "settings" dict below in the same format as the
  shared file and save: a background job rebuilds the file and restarts
  Vorssaint within a few seconds. Example:
    <key>linearScrollLines</key><integer>5</integer>
-->
<plist version="1.0">
<dict>
  <key>settings</key>
  <dict>
  </dict>
  <key>vorssaintBackupVersion</key><integer>1</integer>
</dict>
</plist>
"""


class SettingsError(Exception):
    """A source file is missing or isn't a valid plist."""


def ensure_private() -> bool:
    """Create the private overlay from the template once. True if created."""
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    if PRIVATE.exists():
        return False
    PRIVATE.write_text(PRIVATE_TEMPLATE)
    return True


def render() -> tuple[str, int]:
    """Return (merged file text, number of settings). Raises SettingsError."""
    try:
        shared = plistlib.loads(SHARED.read_bytes())
        private = plistlib.loads(PRIVATE.read_bytes()) if PRIVATE.exists() else {}
    except (OSError, plistlib.InvalidFileException, ValueError, ExpatError) as exc:
        raise SettingsError(f"{exc}") from exc
    settings = {**shared.get("settings", {}), **private.get("settings", {})}
    merged = {**shared, "settings": settings}
    header = (f"<!-- {GENERATED_MARKER}: do not edit. Edit the repo's\n"
              f"     {SHARED_REL} or {PRIVATE.name} next to\n"
              "     this file; it is rebuilt and Vorssaint restarted on save. -->\n")
    decl, rest = plistlib.dumps(merged, sort_keys=True).decode().split("\n", 1)
    return f"{decl}\n{header}{rest}", len(settings)


def write(text: str) -> str | None:
    """Write the merged file. Backs up a hand-made one (no marker) first and
    returns the backup path, if any."""
    backup = None
    if TARGET.is_symlink() or (
            TARGET.exists() and GENERATED_MARKER not in TARGET.read_text(errors="ignore")):
        stamp = datetime.now().strftime("%Y%m%d%H%M%S")
        backup = TARGET.with_name(f"{TARGET.name}.devenv-backup.{stamp}")
        TARGET.rename(backup)
    TARGET.write_text(text)
    return str(backup) if backup else None


def is_running() -> bool:
    return subprocess.run(["pgrep", "-x", "Vorssaint"], capture_output=True).returncode == 0


def quit_and_wait() -> None:
    """Quit Vorssaint and wait for it to exit: an `open` that lands while it is
    still quitting reaches the dying instance, and nothing relaunches."""
    subprocess.run(["osascript", "-e", 'quit app "Vorssaint"'], capture_output=True)
    for _ in range(40):
        if not is_running():
            return
        time.sleep(0.25)


def _notify(message: str) -> None:
    subprocess.run(["osascript", "-e", "on run argv",
                    "-e", 'display notification (item 1 of argv) with title "Vorssaint settings"',
                    "-e", "end run", message], capture_output=True)


def apply() -> int:
    """LaunchAgent entry: rebuild the file; restart Vorssaint if it changed."""
    try:
        ensure_private()
        text, count = render()
    except SettingsError as exc:
        # Usually a save mid-edit; keep the last good file and say why.
        print(f"{datetime.now():%F %T} not applied: {exc}", file=sys.stderr)
        _notify(f"Not applied: a settings file has an error ({exc})")
        return 1
    current = TARGET.read_text(errors="ignore") if TARGET.exists() else None
    if text == current:
        return 0
    was_running = is_running()
    if was_running:
        quit_and_wait()
    write(text)
    if was_running:
        subprocess.run(["open", "-a", "Vorssaint"], capture_output=True)
    print(f"{datetime.now():%F %T} applied {count} settings"
          f"{' and restarted Vorssaint' if was_running else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(apply())
